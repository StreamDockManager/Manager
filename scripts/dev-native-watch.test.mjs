import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import test from 'node:test';
import { watchNativeSources } from './dev-native-watch.mjs';

// Build a disposable workspace with the same layout as the desktop checkout
async function workspace(t, paths) {
    const root = await mkdtemp(join(tmpdir(), 'sdm-native-watch-'));
    t.after(() => rm(root, { recursive: true, force: true }));
    for (const path of paths) {
        await mkdir(dirname(join(root, path)), { recursive: true });
        await writeFile(join(root, path), '');
    }
    return root;
}

// Allow OS filesystem notifications to arrive without depending on one fixed scheduler delay
async function until(condition) {
    const deadline = Date.now() + 5000;
    while (!condition() && Date.now() < deadline) await delay(25);
    assert.ok(condition(), 'expected the watcher to report a change');
}

test('native watcher observes workspace, crate and Tauri inputs and coalesces a save burst', async (t) => {
    const inputs = [
        'Cargo.toml',
        'Cargo.lock',
        'crates/runtime/Cargo.toml',
        'crates/runtime/src/nested/file.rs',
        'src-tauri/src/main.rs',
        'src-tauri/tauri.macos.conf.json',
        'src-tauri/Info.plist',
        'src-tauri/capabilities/main.json',
        'src-tauri/permissions/custom.toml',
    ];
    const root = await workspace(t, inputs);
    const errors = [];
    let changes = 0;
    const close = watchNativeSources(
        root,
        () => changes++,
        (error) => errors.push(error),
    );
    t.after(close);
    // macOS may deliver recent fixture creation events immediately after registration
    await delay(650);
    changes = 0;
    for (const [index, path] of inputs.entries()) {
        await writeFile(join(root, path), 'changed');
        await until(() => changes === index + 1);
    }

    // Editors can save by renaming a temporary file rather than modifying the inode
    await writeFile(join(root, 'crates/runtime/src/nested/file.tmp'), 'atomic save');
    await rename(
        join(root, 'crates/runtime/src/nested/file.tmp'),
        join(root, 'crates/runtime/src/nested/file.rs'),
    );
    await writeFile(join(root, 'src-tauri/src/main.rs'), 'part of burst');
    await until(() => changes === inputs.length + 1);
    await delay(650);
    assert.equal(changes, inputs.length + 1);
    assert.deepEqual(errors, []);
});

test('native watcher ignores artifacts and does not fire after an idempotent cleanup', async (t) => {
    const outputs = [
        'src/styles.css',
        'target/generated.rs',
        'crates/runtime/target/generated.rs',
        'src-tauri/gen/Cargo.toml',
        'src-tauri/permissions/autogenerated/example.toml',
        'src-tauri/src/generated/contract.rs',
    ];
    const input = 'src-tauri/src/main.rs';
    const root = await workspace(t, [...outputs, input, 'crates/runtime/Cargo.toml']);
    const errors = [];
    let changes = 0;
    const close = watchNativeSources(
        root,
        () => changes++,
        (error) => errors.push(error),
    );
    t.after(close);
    // macOS may deliver recent fixture creation events immediately after registration
    await delay(650);
    changes = 0;
    for (const path of outputs) await writeFile(join(root, path), 'ignored');
    await delay(1000);
    assert.equal(changes, 0);

    await writeFile(join(root, input), 'before cleanup');
    close();
    close();
    await writeFile(join(root, input), 'after cleanup');
    await delay(650);
    assert.equal(changes, 0);
    assert.deepEqual(errors, []);
});

test('native watcher reports setup failure and returns a safe disposer', async (t) => {
    const root = await workspace(t, ['Cargo.toml', 'crates/runtime/Cargo.toml']);
    const errors = [];
    const close = watchNativeSources(root, assert.fail, (error) => errors.push(error));
    t.after(close);
    await until(() => errors.length === 1);
    assert.equal(errors[0].code, 'ENOENT');
    close();
});

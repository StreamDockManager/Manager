// Run this executable entry point
fn main() {
    println!("cargo:rerun-if-env-changed=RELEASE_COMMIT");
    if let Ok(commit) = std::env::var("RELEASE_COMMIT") {
        if commit.len() == 40 && commit.bytes().all(|b| b.is_ascii_hexdigit()) {
            println!("cargo:rustc-env=SDM_BUILD_COMMIT={commit}");
        }
    }

    let root = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap())
        .parent()
        .unwrap()
        .to_path_buf();
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=capabilities");
    println!("cargo:rerun-if-changed=../generated/commands.ts");
    println!("cargo:rerun-if-changed=../generated/runtime.ts");
    let commands =
        stream_dock_manager_desktop_contract::discover(&root).expect("Desktop command discovery");
    stream_dock_manager_desktop_contract::validate_capabilities(&root, &commands)
        .expect("Desktop command capability policy");
    let runtime = std::fs::read_to_string(root.join("generated/runtime.ts")).unwrap();
    let expected = stream_dock_manager_desktop_contract::typescript(&commands, &runtime)
        .expect("Desktop command types");
    assert!(
        std::fs::read_to_string(root.join("generated/commands.ts")).unwrap_or_default() == expected,
        "Stale desktop contracts; run cargo run -p xtask -- types"
    );
    let output = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(
        output.join("command_handler.rs"),
        stream_dock_manager_desktop_contract::handler(&commands),
    )
    .expect("Desktop command registration");
    // Tauri retains static references. This is a bounded allocation in the one-shot
    // build process, never in the desktop runtime.
    let names: &'static [&'static str] = Box::leak(
        commands
            .iter()
            .map(|command| &*Box::leak(command.name.clone().into_boxed_str()))
            .collect::<Vec<_>>()
            .into_boxed_slice(),
    );
    // Retire stale derived permissions before Tauri builds its ACL inventory
    // Tauri writes current entries but does not delete prior commands
    let permissions = root.join("src-tauri/permissions/autogenerated");
    for entry in std::fs::read_dir(&permissions).expect("Generated permission directory") {
        let path = entry.expect("Generated permission entry").path();
        if path
            .extension()
            .is_some_and(|extension| extension == "toml")
            && path
                .file_stem()
                .and_then(|stem| stem.to_str())
                .is_some_and(|name| !names.contains(&name))
            && std::fs::read_to_string(&path)
                .expect("Generated permission contents")
                .starts_with("# Automatically generated - DO NOT EDIT!")
        {
            std::fs::remove_file(path).expect("Retire obsolete generated permission");
        }
    }
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(names)),
    )
    .expect("Tauri permission generation");
}
